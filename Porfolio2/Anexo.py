option = input("Option [1-3, q]: ")

if option == "1":
    print("Show disk usage")

elif option == "2":
    print("Show users")

elif option == "3" or option == "r":
    print("Restart service")

elif option == "q":
    print("Bye!!")
    
else:
    print("Unknown option")

